export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  className?: string;
  style?: CSSProperties;
  "aria-hidden"?: boolean | "true" | "false";
  "aria-label"?: string;
}

const ICON_NAMES = Object.keys(ICONS) as IconName[];

export function Icon({ name, className, style, ...aria }: IconProps) {
  if (!isBuiltinIconName(name)) throw new Error(`Unknown Specs icon: ${name}`);
  const label = aria["aria-label"];
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      className={className}
      style={style}
      role={label === undefined ? undefined : "img"}
      aria-label={label}
      aria-hidden={label === undefined ? (aria["aria-hidden"] ?? true) : aria["aria-hidden"]}
    >
      {ICONS[name]}
    </svg>
  );
}

export function isBuiltinIconName(name: string): name is IconName {
  return Object.hasOwn(ICONS, name);
}

export function iconNames(): readonly IconName[] {
  return ICON_NAMES;
}
